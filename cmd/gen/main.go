func writeFunctionsGen(path, version string, descs []*FuncDescriptor) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/gen %s. DO NOT EDIT.\n\npackage ta\n\n", version)
	buf.WriteString("/*\n#include \"ta_func.h\"\n*/\nimport \"C\"\n\n")

	for _, d := range descs {
		writeFunc(&buf, d)
		buf.WriteByte('\n')
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fail("functions_gen.go format failed: %v", err)
	}
	must(os.WriteFile(path, out, 0o644))
}

func writeLookbackGen(path, version string, descs []*FuncDescriptor) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/gen %s. DO NOT EDIT.\n\npackage ta\n\n", version)
	buf.WriteString(`/*
#include "ta_func.h"
*/
import "C"
`)
	buf.WriteByte('\n')

	for _, d := range descs {
		writeLookback(&buf, d)
		buf.WriteByte('\n')
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fail("lookback_gen.go format failed: %v", err)
	}
	must(os.WriteFile(path, out, 0o644))
}

func writeFunc(w *bytes.Buffer, d *FuncDescriptor) {
	// Doc comment.
	if d.DocComment != "" {
		for _, line := range strings.Split(d.DocComment, "\n") {
			if line == "" {
				fmt.Fprintln(w, "//")
			} else {
				fmt.Fprintf(w, "// %s\n", line)
			}
		}
	}

	// Build function signature.
	var params []string

	// Input arrays.
	for _, p := range d.Inputs {
		goType := "[]float64"
		if p.CType == "int" {
			goType = "[]int32"
		}
		params = append(params, fmt.Sprintf("%s %s", p.GoName, goType))
	}

	// Optional inputs (scalar params).
	for _, p := range d.OptIns {
		goType := "int"
		if p.CType == "double" {
			goType = "float64"
		}
		params = append(params, fmt.Sprintf("%s %s", p.GoName, goType))
	}

	// Output buffer params — always use shortened buf names to allow named returns.
	for _, p := range d.Outputs {
		goType := "[]float64"
		if p.CType == "int" {
			goType = "[]int32"
		}
		params = append(params, fmt.Sprintf("%s %s", outBufParamName(p.GoName), goType))
	}

	// Named return types — always named for documentation clarity.
	var retParts []string
	for _, p := range d.Outputs {
		goType := "[]float64"
		if p.CType == "int" {
			goType = "[]int32"
		}
		retParts = append(retParts, fmt.Sprintf("%s %s", p.GoName, goType))
	}
	retStr := " (" + strings.Join(retParts, ", ") + ")"

	fmt.Fprintf(w, "func %s(%s)%s {\n", d.GoName, strings.Join(params, ", "), retStr)

	const badParam = "\t\tpanic(&TALibError{RetCode: 2, Message: retCodeMessage(2)})\n"
	const internalError = "\t\tpanic(&TALibError{RetCode: 5000, Message: retCodeMessage(5000)})\n"

	// Guard: require at least one input element, and inputs of equal length (C reads
	// every input up to the first one's length).
	if len(d.Inputs) > 0 {
		firstIn := d.Inputs[0].GoName
		fmt.Fprintf(w, "\tif len(%s) == 0 {\n%s\t}\n", firstIn, badParam)
		var mismatch []string
		for _, p := range d.Inputs[1:] {
			mismatch = append(mismatch, fmt.Sprintf("len(%s) != len(%s)", p.GoName, firstIn))
		}
		if len(mismatch) > 0 {
			fmt.Fprintf(w, "\tif %s {\n%s\t}\n", strings.Join(mismatch, " || "), badParam)
		}
	}

	// Lookback call. A negative lookback means an optional input is out of range.
	lookbackArgs := buildLookbackArgs(d)
	fmt.Fprintf(w, "\tlookback := int(C.TA_%s_Lookback(%s))\n", d.Name, lookbackArgs)
	fmt.Fprintf(w, "\tif lookback < 0 {\n%s\t}\n", badParam)

	// Determine length from first input.
	if len(d.Inputs) > 0 {
		fmt.Fprintf(w, "\tn := len(%s)\n", d.Inputs[0].GoName)
	}

	// Allocate output buffers.
	var realIns []string
	for _, p := range d.Inputs {
		if p.CType == "double" {
			realIns = append(realIns, ", "+p.GoName)
		}
	}
	for _, p := range d.Outputs {
		ins := ""
		if p.CType == "double" {
			ins = strings.Join(realIns, "")
		}
		fmt.Fprintf(w, "\t%s = reuseOrAlloc%s(%s, n%s)\n", p.GoName, allocSuffix(p.CType), outBufParamName(p.GoName), ins)
		fmt.Fprintf(w, "\tfillNaN%s(%s[:min(lookback, n)])\n", nanSuffix(p.CType), p.GoName)
	}

	// Too short for any output: everything is warmup, and the out[lookback:] passed to C
	// below would be empty or out of range.
	var outNames []string
	for _, p := range d.Outputs {
		outNames = append(outNames, p.GoName)
	}
	fmt.Fprintf(w, "\tif n <= lookback {\n\t\treturn %s\n\t}\n", strings.Join(outNames, ", "))

	// Call TA function.
	fmt.Fprintf(w, "\tvar begIdx, nbElem C.int\n")

	callArgs := buildCallArgs(d)
	fmt.Fprintf(w, "\trc := C.TA_%s(0, cInt(n-1),\n\t\t%s,\n\t\t&begIdx, &nbElem,\n\t\t%s)\n",
		d.Name,
		callArgs,
		buildOutPtrs(d),
	)
	fmt.Fprintf(w, "\tcheckRC(rc)\n")
	// C wrote from begIdx into out[lookback:]; any other begIdx means TA_X and
	// TA_X_Lookback disagree.
	fmt.Fprintf(w, "\tif int(begIdx) != lookback {\n%s\t}\n", internalError)

	// Fill any remainder with NaN/zero defensively.
	for _, p := range d.Outputs {
		fmt.Fprintf(w, "\tfillNaN%s(%s[lookback+int(nbElem):])\n", nanSuffix(p.CType), p.GoName)
	}

	// Return.
	fmt.Fprintf(w, "\treturn %s\n", strings.Join(outNames, ", "))

	fmt.Fprintln(w, "}")
}

func allocSuffix(ctype string) string {
	if ctype == "int" {
		return "Int32"
	}
	return ""
}

func nanSuffix(ctype string) string {
	if ctype == "int" {
		return "Int32"
	}
	return ""
}

func buildLookbackArgs(d *FuncDescriptor) string {
	var args []string
	for _, p := range d.OptIns {
		switch p.CType {
		case "double":
			args = append(args, fmt.Sprintf("C.double(%s)", p.GoName))
		case "TA_MAType":
			args = append(args, fmt.Sprintf("C.TA_MAType(cInt(%s))", p.GoName))
		default:
			args = append(args, fmt.Sprintf("cInt(%s)", p.GoName))
		}
	}
	return strings.Join(args, ", ")
}

func buildCallArgs(d *FuncDescriptor) string {
	var args []string
	for _, p := range d.Inputs {
		if p.CType == "int" {
			args = append(args, fmt.Sprintf("inPtrInt(%s)", p.GoName))
		} else {
			args = append(args, fmt.Sprintf("inPtr(%s)", p.GoName))
		}
	}
	for _, p := range d.OptIns {
		switch p.CType {
		case "double":
			args = append(args, fmt.Sprintf("C.double(%s)", p.GoName))
		case "TA_MAType":
			args = append(args, fmt.Sprintf("C.TA_MAType(cInt(%s))", p.GoName))
		default:
			args = append(args, fmt.Sprintf("cInt(%s)", p.GoName))
		}
	}
	return strings.Join(args, ",\n\t\t")
}

func buildOutPtrs(d *FuncDescriptor) string {
	var args []string
	for _, p := range d.Outputs {
		if p.CType == "int" {
			args = append(args, fmt.Sprintf("inPtrInt(%s[lookback:])", p.GoName))
		} else {
			args = append(args, fmt.Sprintf("inPtr(%s[lookback:])", p.GoName))
		}
	}
	return strings.Join(args, ",\n\t\t")
}

