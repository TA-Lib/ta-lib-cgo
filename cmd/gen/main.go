func writeLookback(w *bytes.Buffer, d *FuncDescriptor) {
	// Build params from OptIns only (same as LookbackSig).
	var params []string
	for _, p := range d.OptIns {
		goType := "int"
		if p.CType == "double" {
			goType = "float64"
		} else if p.CType == "TA_MAType" {
			goType = "int"
		}
		params = append(params, fmt.Sprintf("%s %s", p.GoName, goType))
	}

	fmt.Fprintf(w, "// %sLookback returns the number of input values consumed before the first valid output,\n", d.GoName)
	fmt.Fprintf(w, "// or -1 when a parameter is out of range.\n")
	fmt.Fprintf(w, "func %sLookback(%s) int {\n", d.GoName, strings.Join(params, ", "))

	var unfit []string
	for _, p := range d.OptIns {
		if p.CType != "double" {
			unfit = append(unfit, fmt.Sprintf("!fitsCInt(%s)", p.GoName))
		}
	}
	if len(unfit) > 0 {
		fmt.Fprintf(w, "\tif %s {\n\t\treturn -1\n\t}\n", strings.Join(unfit, " || "))
	}

	cArgs := buildLookbackArgs(d)
	fmt.Fprintf(w, "\treturn int(C.TA_%s_Lookback(%s))\n", d.Name, cArgs)
	fmt.Fprintln(w, "}")
}

// modulePath reads the module path from go.mod.
func modulePath(repoRoot string) string {
	data, err := os.ReadFile(filepath.Join(repoRoot, "go.mod"))
	must(err)
	for _, line := range strings.Split(string(data), "\n") {
		if f := strings.Fields(line); len(f) == 2 && f[0] == "module" {
			return f[1]
		}
	}
	fail("no module line in go.mod")
	return ""
}

// goldenInputs binds each C input parameter to a series of goldenInput in golden_test.go.
// cmd/golden/c/dump.c binds the official library's inputs by the same rule.
var goldenInputs = map[string]string{
	"inOpen":    "open",
	"inHigh":    "high",
	"inLow":     "low",
	"inClose":   "close",
	"inVolume":  "volume",
	"inReal":    "close",
	"inReal0":   "close",
	"inReal1":   "real1",
	"inPeriods": "periods",
}

// writeGoldenGen writes the table golden_test.go walks: for every function, its output
// names and a call of the wrapper with the default optional inputs.
func writeGoldenGen(path, version, module string, descs []*FuncDescriptor) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/gen %s. DO NOT EDIT.\n\npackage ta_test\n\n", version)
	fmt.Fprintf(&buf, "import ta %q\n\n", module)
	buf.WriteString("var goldenFuncs = []goldenFunc{\n")
	for _, d := range descs {
		var args, outs, names []string
		for _, p := range d.Inputs {
			series, ok := goldenInputs[p.Name]
			if !ok || p.CType != "double" {
				fail("TA_%s: no golden binding for input %s %s", d.Name, p.CType, p.Name)
			}
			args = append(args, "in."+series)
		}
		for _, p := range d.OptIns {
			if p.Default == "" {
				fail("TA_%s: no default for %s", d.Name, p.Name)
			}
			args = append(args, p.Default)
		}
		for i, p := range d.Outputs {
			args = append(args, "nil")
			outs = append(outs, fmt.Sprintf("o%d", i))
			names = append(names, strconv.Quote(p.Name))
		}
		o := strings.Join(outs, ", ")
		fmt.Fprintf(&buf, "\t{%q, []string{%s}, func(in *goldenInput) []any {\n\t\t%s := ta.%s(%s)\n\t\treturn []any{%s}\n\t}},\n",
			d.Name, strings.Join(names, ", "), o, d.GoName, strings.Join(args, ", "), o)
	}
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fail("golden_gen_test.go format failed: %v", err)
	}
	must(os.WriteFile(path, out, 0o644))
}
