// cmd/gen clones the TA-Lib repository at a pinned version, builds the amalgamation
// C files, copies headers, and generates Go wrapper source files.
//
// Usage: go run ./cmd/gen <version-tag>
// Example: go run ./cmd/gen v0.8.3
package main

import (
	"bufio"
	"bytes"
	"encoding/csv"
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: go run ./cmd/gen <version-tag>")
		os.Exit(1)
	}
	version := os.Args[1]

	// Determine repository root by walking up from the working directory to find go.mod.
	// go generate sets the working directory to the package directory, so cwd is the repo root.
	repoRoot, err := os.Getwd()
	must(err)
	for {
		if _, err := os.Stat(filepath.Join(repoRoot, "go.mod")); err == nil {
			break
		}
		parent := filepath.Dir(repoRoot)
		if parent == repoRoot {
			fmt.Fprintln(os.Stderr, "could not find module root (no go.mod found)")
			os.Exit(1)
		}
		repoRoot = parent
	}

	fmt.Printf("cgo-ta-lib gen: version=%s root=%s\n", version, repoRoot)

	// Step 1: Clone TA-Lib into a temp directory.
	tmpDir, err := os.MkdirTemp("", "ta-lib-clone-*")
	must(err)
	defer os.RemoveAll(tmpDir)

	fmt.Printf("Cloning TA-Lib %s into %s...\n", version, tmpDir)
	runCmd("git", "clone", "--depth=1", "--branch", version,
		"https://github.com/TA-Lib/ta-lib", tmpDir)

	// Step 2: Read the C sources to embed.
	// ta_config.h is generated by the TA-Lib build, which this generator does not run.
	sources := readSources(tmpDir)
	for _, s := range sources {
		if reConfigInclude.Match(s.data) {
			fail("%s includes ta_config.h: TA-Lib %s is not supported by this generator", s.rel, version)
		}
	}

	// Step 3: Copy headers.
	// include/ gets public headers + all internal headers from src/ subdirectories.
	// The amalgamation uses #include "internal_header.h" (unqualified), so all
	// headers must be findable from a single -I path.
	includeDir := filepath.Join(repoRoot, "include")
	must(os.MkdirAll(includeDir, 0o755))
	removeFiles(includeDir)

	copyDirGlob(filepath.Join(tmpDir, "include"), includeDir, ".h")

	// Copy internal headers from each src/ subdirectory.
	for _, sub := range []string{"ta_common", "ta_func", "ta_abstract"} {
		copyDirGlob(filepath.Join(tmpDir, "src", sub), includeDir, ".h")
	}

	// Step 4: Build amalgamation.
	fmt.Println("Building amalgamation...")
	buildAmalgamation(sources, repoRoot, version)

	// Step 5: Parse ta_retcode.csv and write errors_gen.go.
	fmt.Println("Generating errors_gen.go...")
	csvPath := filepath.Join(tmpDir, "ta_retcode.csv")
	// Some versions embed it elsewhere; try a few locations.
	if _, err := os.Stat(csvPath); os.IsNotExist(err) {
		csvPath = filepath.Join(tmpDir, "src", "ta_common", "ta_retcode.csv")
	}
	retCodes := parseRetCodeCSV(csvPath)
	writeErrorsGen(filepath.Join(repoRoot, "errors_gen.go"), version, retCodes)

	// Step 6 & 7: Parse ta_func.h and extract doc comments from .c files.
	fmt.Println("Parsing ta_func.h...")
	taFuncH := filepath.Join(includeDir, "ta_func.h")
	funcDescs := parseTaFuncH(taFuncH)
	checkFuncAPI(filepath.Join(tmpDir, "ta_func_api.xml"), funcDescs)

	extractDocComments(funcDescs, taFuncH)

	// Step 8: Generate functions_gen.go.
	fmt.Println("Generating functions_gen.go...")
	writeFunctionsGen(filepath.Join(repoRoot, "functions_gen.go"), version, funcDescs)

	// Step 9: Generate lookback_gen.go.
	fmt.Println("Generating lookback_gen.go...")
	writeLookbackGen(filepath.Join(repoRoot, "lookback_gen.go"), version, funcDescs)

	fmt.Println("Generating golden_gen_test.go...")
	writeGoldenGen(filepath.Join(repoRoot, "golden_gen_test.go"), version, modulePath(repoRoot), funcDescs)

	// Step 10: Generate version_gen.go.
	fmt.Println("Generating version_gen.go...")
	writeVersionGen(filepath.Join(repoRoot, "version_gen.go"), version)

	fmt.Println("Done.")
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

func runCmd(name string, args ...string) {
	cmd := exec.Command(name, args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		fmt.Fprintf(os.Stderr, "command %s %v failed: %v\n", name, args, err)
		os.Exit(1)
	}
}

// removeFiles deletes the files directly in dir, so headers a newer TA-Lib dropped do not linger.
func removeFiles(dir string) {
	entries, err := os.ReadDir(dir)
	must(err)
	for _, e := range entries {
		if !e.IsDir() {
			must(os.Remove(filepath.Join(dir, e.Name())))
		}
	}
}

// copyDirGlob copies files from src to dst, optionally filtering by extension (e.g. ".h").
func copyDirGlob(src, dst, ext string) {
	entries, err := os.ReadDir(src)
	must(err)
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		if ext != "" && !strings.HasSuffix(e.Name(), ext) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(src, e.Name()))
		must(err)
		must(os.WriteFile(filepath.Join(dst, e.Name()), data, 0o644))
	}
}

// srcFile is one TA-Lib C source file to embed.
type srcFile struct {
	rel  string // path inside the TA-Lib clone, e.g. "src/ta_func/ta_SMA.c"
	name string // base name, e.g. "ta_SMA.c"
	data []byte
}

var reConfigInclude = regexp.MustCompile(`(?m)^\s*#\s*include\s*["<]ta_config\.h[">]`)

// readSources reads the C source files that make up the amalgamation.
func readSources(tmpDir string) []srcFile {
	var files []srcFile
	appendDir := func(dir, glob string) {
		entries, err := filepath.Glob(filepath.Join(tmpDir, dir, glob))
		if err != nil || len(entries) == 0 {
			fail("no files matched %s in %s", glob, dir)
		}
		sort.Strings(entries)
		for _, path := range entries {
			data, err := os.ReadFile(path)
			if err != nil {
				fail("could not read %s: %v", path, err)
			}
			name := filepath.Base(path)
			files = append(files, srcFile{rel: filepath.Join(dir, name), name: name, data: data})
		}
	}

	appendDir(filepath.Join("src", "ta_common"), "*.c")
	appendDir(filepath.Join("src", "ta_func"), "ta_*.c")
	return files
}

// amalgamationShards is the number of talib_amalgamation_NN.c files. cgo compiles each
// as its own translation unit, in parallel; one file of everything is several times
// slower to build and needs most of a gigabyte of compiler memory.
const amalgamationShards = 16

// buildAmalgamation concatenates the C source files into amalgamationShards files,
// keeping each source file whole. Every TA-Lib source file is self-contained, so any
// split links.
func buildAmalgamation(sources []srcFile, repoRoot, version string) {
	old, err := filepath.Glob(filepath.Join(repoRoot, "talib_amalgamation*.c"))
	must(err)
	for _, path := range old {
		must(os.Remove(path))
	}

	// Largest file first onto the lightest shard. Every tie is broken by name or index,
	// so the same sources always give the same shards.
	bySize := append([]srcFile(nil), sources...)
	sort.Slice(bySize, func(i, j int) bool {
		if len(bySize[i].data) != len(bySize[j].data) {
			return len(bySize[i].data) > len(bySize[j].data)
		}
		return lessByName(bySize[i], bySize[j])
	})
	shards := make([][]srcFile, amalgamationShards)
	sizes := make([]int, amalgamationShards)
	for _, s := range bySize {
		lightest := 0
		for i := range sizes {
			if sizes[i] < sizes[lightest] {
				lightest = i
			}
		}
		shards[lightest] = append(shards[lightest], s)
		sizes[lightest] += len(s.data)
	}

	for i, files := range shards {
		sort.Slice(files, func(a, b int) bool { return lessByName(files[a], files[b]) })

		var buf bytes.Buffer
		fmt.Fprintf(&buf, "// Code generated by cmd/gen %s. DO NOT EDIT.\n\n", version)
		// TA-Lib's own build compiles with -ffp-contract=off and its results depend on it.
		// cgo rejects that flag in #cgo CFLAGS, so each translation unit asks for it ahead
		// of any include; the #ifdef keeps each compiler off the other's pragma.
		buf.WriteString("#ifdef __clang__\n#pragma STDC FP_CONTRACT OFF\n#else\n#pragma GCC optimize (\"fp-contract=off\")\n#endif\n\n")
		// Suppress GCC's -Wstringop-overflow false positive on the ARRAY_MEMMOVE macro
		// in ta_memory.h. GCC incorrectly infers the memmove bound could overflow when
		// size (signed int) is multiplied by sizeof(type) (unsigned).
		// Clang defines __clang__ and does not have this warning; the guard prevents
		// Clang from warning about an unknown warning group in the pragma.
		buf.WriteString("#ifndef __clang__\n#pragma GCC diagnostic ignored \"-Wstringop-overflow\"\n#endif\n\n")

		for _, s := range files {
			fmt.Fprintf(&buf, "// --- %s ---\n", s.name)
			// Each ta_func file redefines TA_PREFIX and INPUT_TYPE. Undef first to
			// prevent redefinition warnings across the concatenated translation unit.
			// #undef on an undefined macro is a no-op, so this is safe everywhere.
			buf.WriteString("#undef TA_PREFIX\n#undef INPUT_TYPE\n")
			buf.Write(s.data)
			buf.WriteByte('\n')
		}

		outPath := filepath.Join(repoRoot, fmt.Sprintf("talib_amalgamation_%02d.c", i+1))
		must(os.WriteFile(outPath, buf.Bytes(), 0o644))
	}
}

func lessByName(a, b srcFile) bool {
	if a.name != b.name {
		return a.name < b.name
	}
	return a.rel < b.rel
}

// --- Error code parsing ---

type retCode struct {
	code int
	name string
	desc string
}

func parseRetCodeCSV(path string) []retCode {
	f, err := os.Open(path)
	if err != nil {
		fail("could not open %s: %v", path, err)
	}
	defer f.Close()

	r := csv.NewReader(f)
	r.Comment = '#'
	r.FieldsPerRecord = -1

	var codes []retCode
	for {
		record, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil || len(record) < 3 {
			continue
		}
		var code int
		fmt.Sscanf(strings.TrimSpace(record[0]), "%d", &code)
		name := strings.TrimSpace(record[1])
		desc := strings.TrimSpace(record[2])
		codes = append(codes, retCode{code, name, desc})
	}
	if len(codes) == 0 {
		fail("no return codes found in %s", path)
	}
	return codes
}

func writeErrorsGen(path, version string, codes []retCode) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/gen %s. DO NOT EDIT.\n\npackage ta\n\n", version)
	buf.WriteString("var retCodeMessages = map[int]string{\n")
	for _, c := range codes {
		fmt.Fprintf(&buf, "\t%d: %q,\n", c.code, fmt.Sprintf("%s(%d): %s", c.name, c.code, c.desc))
	}
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fail("errors_gen.go format failed: %v", err)
	}
	must(os.WriteFile(path, out, 0o644))
}

// --- ta_func.h parsing ---

// FuncDescriptor holds everything needed to generate one wrapper function.
type FuncDescriptor struct {
	Name        string  // e.g. "ADX"
	GoName      string  // e.g. "Adx"
	Inputs      []Param // double[] or integer[] inputs
	OptIns      []Param // optional integer/double/MAType params
	Outputs     []Param // double[] or integer[] outputs
	LookbackSig string  // raw C parameter list for Lookback, e.g. "int optInTimePeriod"
	DocComment  string  // extracted from .c file
}

type Param struct {
	CType   string // "double", "int", "TA_Integer", "TA_MAType"
	Name    string // e.g. "inHigh", "optInTimePeriod", "outReal"
	GoName  string // camelCase Go name
	Default string // optional inputs only: Go literal of the ta_func_api.xml default
}

var (
	// TA_LIB_API prefix is present in v0.6.x headers. Match both with and without it.
	// Skip TA_S_ variants (single-precision float versions of each function).
	// Only batch functions take startIdx first; the streaming API (TA_SMA_Open, ...)
	// also returns TA_RetCode.
	reFuncStart     = regexp.MustCompile(`(?:TA_LIB_API\s+)?TA_RetCode\s+TA_([A-Z0-9_]+)\s*\(\s*int\s+startIdx`)
	reLookbackStart = regexp.MustCompile(`(?:TA_LIB_API\s+)?int\s+TA_([A-Z0-9_]+?)_Lookback\s*\((.*)`)
	reCComment      = regexp.MustCompile(`/\*.*?\*/`)
	reParamLine     = regexp.MustCompile(`^\s*(const\s+)?(double|TA_Real|TA_Integer|int|TA_MAType)\s+[\*]?(in|optIn|out)([A-Za-z0-9_]+)`)
	// reDocLine matches the function-description line inside a GENCODE SECTION 3 comment block.
	reDocLine = regexp.MustCompile(`^\s*\*\s+TA_([A-Z0-9_]+)\s+-\s+`)
	// reOptIn matches optIn-prefixed parameter names in doc comment text.
	reOptIn = regexp.MustCompile(`optIn([A-Z][A-Za-z0-9]*)`)
)

// outParamSkip are internal TA-Lib output parameters that are not data arrays.
var outParamSkip = map[string]bool{"BegIdx": true, "NBElement": true}

func parseTaFuncH(path string) []*FuncDescriptor {
	f, err := os.Open(path)
	must(err)
	defer f.Close()

	byName := map[string]*FuncDescriptor{}
	var order []string
	hasLookback := map[string]bool{}

	scanner := bufio.NewScanner(f)
	var current *FuncDescriptor
	inFunc := false

	for scanner.Scan() {
		line := scanner.Text()

		// Lookback signature — one line per parameter when there are several.
		if m := reLookbackStart.FindStringSubmatch(line); m != nil {
			name := m[1]
			// Skip TA_S_ variants (single-precision).
			if strings.HasPrefix(name, "S_") {
				continue
			}
			decl := reCComment.ReplaceAllString(m[2], "")
			for !strings.Contains(decl, ")") && scanner.Scan() {
				decl += " " + reCComment.ReplaceAllString(scanner.Text(), "")
			}
			end := strings.Index(decl, ")")
			if end < 0 {
				fail("%s: unterminated TA_%s_Lookback declaration", path, name)
			}
			sig := strings.Join(strings.Fields(decl[:end]), " ")
			if d, ok := byName[name]; ok {
				d.LookbackSig = sig
				hasLookback[name] = true
			}
			continue
		}

		// Function start.
		if m := reFuncStart.FindStringSubmatch(line); m != nil {
			name := m[1]
			// Skip TA_S_ variants (single-precision).
			if strings.HasPrefix(name, "S_") {
				inFunc = false
				current = nil
				continue
			}
			if _, seen := byName[name]; !seen {
				d := &FuncDescriptor{
					Name:   name,
					GoName: toCamel(name),
				}
				byName[name] = d
				order = append(order, name)
			}
			current = byName[name]
			inFunc = true
			continue
		}

		if inFunc {
			trimmed := strings.TrimSpace(line)

			// Try to pick up a param from this line first (e.g. "double outReal[] );").
			if m := reParamLine.FindStringSubmatch(line); m != nil {
				rawType := m[2]
				prefix := m[3] // "in", "optIn", "out"
				suffix := m[4] // e.g. "High", "TimePeriod", "Real"

				if !outParamSkip[suffix] {
					rawName := prefix + suffix
					p := Param{
						CType:  normalizeCType(rawType),
						Name:   rawName,
						GoName: paramGoName(prefix, suffix),
					}
					switch prefix {
					case "in":
						current.Inputs = append(current.Inputs, p)
					case "optIn":
						current.OptIns = append(current.OptIns, p)
					case "out":
						current.Outputs = append(current.Outputs, p)
					}
				}
			}

			// End of function block: ); on its own line, or the last param line ends with );
			if strings.HasPrefix(trimmed, ");") || trimmed == ")" ||
				strings.HasSuffix(trimmed, ");") || strings.HasSuffix(trimmed, ")") {
				inFunc = false
				current = nil
			}
		}
	}
	must(scanner.Err())

	if len(order) == 0 {
		fail("no functions parsed from %s", path)
	}
	result := make([]*FuncDescriptor, 0, len(order))
	for _, name := range order {
		d := byName[name]
		if len(d.Outputs) == 0 {
			fail("%s: no outputs parsed for TA_%s", path, name)
		}
		if !hasLookback[name] {
			fail("%s: no TA_%s_Lookback declaration after TA_%s", path, name, name)
		}
		// The wrappers pass TA_X's optional inputs to TA_X_Lookback, and size the
		// output from its answer.
		var want []string
		for _, p := range d.OptIns {
			want = append(want, p.CType+" "+p.Name)
		}
		if got := lookbackParams(d.LookbackSig); !slices.Equal(got, want) {
			fail("%s: TA_%s_Lookback takes (%s), not the optional inputs of TA_%s (%s)",
				path, name, strings.Join(got, ", "), name, strings.Join(want, ", "))
		}
		result = append(result, d)
	}
	return result
}

// lookbackParams returns "type name" for each parameter of a Lookback declaration,
// with the type normalized as for a function's parameters.
func lookbackParams(sig string) []string {
	if sig == "void" || sig == "" {
		return nil
	}
	var params []string
	for _, p := range strings.Split(sig, ",") {
		f := strings.Fields(p)
		if len(f) < 2 {
			params = append(params, strings.TrimSpace(p))
			continue
		}
		params = append(params, normalizeCType(strings.Join(f[:len(f)-1], " "))+" "+f[len(f)-1])
	}
	return params
}

func normalizeCType(raw string) string {
	switch raw {
	case "TA_Real":
		return "double"
	case "TA_Integer":
		return "int"
	default:
		return raw
	}
}

// toCamel converts "ADX" → "Adx", "MACD" → "Macd", "MINUS_DI" → "MinusDi".
func toCamel(s string) string {
	parts := strings.Split(s, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(strings.ToLower(p[1:]))
	}
	return b.String()
}

// paramGoName converts prefix+suffix to a Go-idiomatic camelCase name.
// "in"+"High" → "high", "optIn"+"TimePeriod" → "timePeriod", "out"+"Real" → "outReal".
func paramGoName(prefix, suffix string) string {
	lower := strings.ToLower(suffix[:1]) + suffix[1:]
	switch prefix {
	case "in":
		// Rename common OHLCV names.
		switch lower {
		case "high":
			return "high"
		case "low":
			return "low"
		case "close", "closePrice":
			return "closePrice"
		case "open":
			return "open"
		case "volume":
			return "volume"
		case "real":
			return "in"
		case "real0":
			return "in0"
		case "real1":
			return "in1"
		default:
			return lower
		}
	case "optIn":
		return lower
	case "out":
		return "out" + strings.ToUpper(suffix[:1]) + suffix[1:]
	}
	return lower
}

// --- ta_func_api.xml cross-check ---

// funcAPI is the part of ta_func_api.xml that checkFuncAPI compares.
type funcAPI struct {
	Funcs []struct {
		Abbreviation string   `xml:"Abbreviation"`
		Inputs       []string `xml:"RequiredInputArguments>RequiredInputArgument>Type"`
		OptIns       []struct {
			Type         string `xml:"Type"`
			DefaultValue string `xml:"DefaultValue"`
		} `xml:"OptionalInputArguments>OptionalInputArgument"`
		Outputs []string `xml:"OutputArguments>OutputArgument>Type"`
	} `xml:"FinancialFunction"`
}

// oneCInput lists the required input types that are exactly one C array parameter.
// Any other type fails the check rather than being miscounted.
var oneCInput = map[string]bool{
	"Open": true, "High": true, "Low": true, "Close": true, "Volume": true,
	"Double Array": true, "Integer Array": true,
}

// optInCType maps a ta_func_api.xml optional input type to its ta_func.h C type.
var optInCType = map[string]string{"Integer": "int", "Double": "double", "MA Type": "TA_MAType"}

// checkFuncAPI fails unless ta_func_api.xml and the ta_func.h parse agree on the set of
// functions and on each one's input, optional input and output counts, and on the type
// of each optional input. It records each optional input's default.
func checkFuncAPI(path string, descs []*FuncDescriptor) {
	data, err := os.ReadFile(path)
	if err != nil {
		fail("could not read %s: %v", path, err)
	}
	var api funcAPI
	if err := xml.Unmarshal(data, &api); err != nil {
		fail("could not parse %s: %v", path, err)
	}

	byName := map[string]*FuncDescriptor{}
	for _, d := range descs {
		byName[d.Name] = d
	}
	var problems []string
	inXML := map[string]bool{}
	for _, f := range api.Funcs {
		inXML[f.Abbreviation] = true
		d, ok := byName[f.Abbreviation]
		if !ok {
			problems = append(problems, fmt.Sprintf("%s: in ta_func_api.xml, not parsed from ta_func.h", f.Abbreviation))
			continue
		}
		for _, t := range f.Inputs {
			if !oneCInput[t] {
				problems = append(problems, fmt.Sprintf("%s: unknown required input type %q in ta_func_api.xml", f.Abbreviation, t))
			}
		}
		compare := func(what string, xmlCount, headerCount int) {
			if xmlCount != headerCount {
				problems = append(problems, fmt.Sprintf("%s: %d %s in ta_func_api.xml, %d in ta_func.h", f.Abbreviation, xmlCount, what, headerCount))
			}
		}
		compare("inputs", len(f.Inputs), len(d.Inputs))
		compare("optional inputs", len(f.OptIns), len(d.OptIns))
		compare("outputs", len(f.Outputs), len(d.Outputs))
		if len(f.OptIns) != len(d.OptIns) {
			continue
		}
		for i, o := range f.OptIns {
			p := &d.OptIns[i]
			if optInCType[o.Type] != p.CType {
				problems = append(problems, fmt.Sprintf("%s: optional input %d is %q in ta_func_api.xml, %s %s in ta_func.h", f.Abbreviation, i, o.Type, p.CType, p.Name))
				continue
			}
			lit, err := goLiteral(p.CType, strings.TrimSpace(o.DefaultValue))
			if err != nil {
				problems = append(problems, fmt.Sprintf("%s: default of %s in ta_func_api.xml: %v", f.Abbreviation, p.Name, err))
				continue
			}
			p.Default = lit
		}
	}
	for _, d := range descs {
		if !inXML[d.Name] {
			problems = append(problems, fmt.Sprintf("%s: parsed from ta_func.h, not in ta_func_api.xml", d.Name))
		}
	}
	if len(problems) > 0 {
		fail("ta_func.h and %s disagree:\n  %s", path, strings.Join(problems, "\n  "))
	}
}

// goLiteral turns a ta_func_api.xml default value into a Go literal of the wrapper's
// parameter type.
func goLiteral(ctype, v string) (string, error) {
	if ctype == "double" {
		f, err := strconv.ParseFloat(v, 64)
		if err != nil {
			return "", err
		}
		return strconv.FormatFloat(f, 'g', -1, 64), nil
	}
	n, err := strconv.Atoi(v)
	if err != nil {
		return "", err
	}
	return strconv.Itoa(n), nil
}

// --- Doc comment extraction ---

// extractDocComments reads ta_func.h and finds the GENCODE SECTION 3 comment block
// for each function. These blocks contain the human-readable Input/Output/Parameters
// description and are identified by the pattern "* TA_FUNCNAME - description".
func extractDocComments(descs []*FuncDescriptor, taFuncH string) {
	data, err := os.ReadFile(taFuncH)
	must(err)
	comments := parseDocComments(string(data))
	for _, d := range descs {
		c, ok := comments[d.Name]
		if !ok {
			fail("%s: no doc comment block for TA_%s", taFuncH, d.Name)
		}
		d.DocComment = transformDocComment(c, d)
	}
}

// parseDocComments scans a header for standalone /* ... */ blocks that
// contain a "* TA_FUNCNAME - description" line (the GENCODE SECTION 3 doc blocks).
// Returns a map from TA-Lib function name (e.g. "ACCBANDS") to cleaned comment body.
func parseDocComments(src string) map[string]string {
	result := map[string]string{}
	lines := strings.Split(src, "\n")
	n := len(lines)
	for i := 0; i < n; i++ {
		// Look for a standalone "/*" that opens a doc block.
		if strings.TrimSpace(lines[i]) != "/*" {
			continue
		}
		blockStart := i + 1
		funcName := ""
		j := blockStart
		for j < n {
			t := strings.TrimSpace(lines[j])
			if t == "*/" {
				break
			}
			if m := reDocLine.FindStringSubmatch(lines[j]); m != nil && funcName == "" {
				funcName = m[1]
			}
			j++
		}
		if funcName != "" {
			var cleaned []string
			for k := blockStart; k < j; k++ {
				cleaned = append(cleaned, cleanCommentLine(lines[k]))
			}
			result[funcName] = strings.Join(trimBlankLines(cleaned), "\n")
		}
		i = j // skip to closing */
	}
	return result
}

// cleanCommentLine strips the leading " * " or " *" from a C block comment line
// and trims any remaining leading/trailing whitespace.
func cleanCommentLine(line string) string {
	s := strings.TrimLeft(line, " \t")
	if after, ok := strings.CutPrefix(s, "* "); ok {
		return strings.TrimSpace(after)
	}
	return strings.TrimSpace(strings.TrimPrefix(s, "*"))
}

// trimBlankLines removes leading and trailing empty lines from a slice.
func trimBlankLines(lines []string) []string {
	for len(lines) > 0 && strings.TrimSpace(lines[0]) == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

// transformDocComment converts a raw TA-Lib GENCODE SECTION 3 comment into a clean
// Go doc comment. It:
//   - Replaces "TA_FUNCNAME - description" with "GoName - description" on the first line.
//   - Reformats Input/Output as separate paragraphs.
//   - Drops the "Optional Parameters / ---" header (redundant).
//   - Converts each parameter block into a Go-style list item:
//     "  - paramName (X to Y): description"
func transformDocComment(comment string, d *FuncDescriptor) string {
	lines := strings.Split(comment, "\n")
	if len(lines) == 0 {
		return comment
	}

	// Fix first line: replace TA_NAME with Go name.
	lines[0] = strings.Replace(lines[0], "TA_"+d.Name+" - ", d.GoName+" - ", 1)

	// Collect Input/Output lines and parameter blocks from the rest.
	var inputOutput []string
	type param struct{ name, rang, desc string }
	var params []param

	// Simple state machine over the remaining lines.
	const (
		stateHeader = iota // before/between sections
		stateParams        // inside the parameters section
	)
	state := stateHeader
	var pendingParam *param

	for _, line := range lines[1:] {
		line = reOptIn.ReplaceAllStringFunc(line, func(match string) string {
			suffix := match[5:]
			return strings.ToLower(suffix[:1]) + suffix[1:]
		})
		trimmed := strings.TrimSpace(line)

		// Skip blanks, section header, and separator line.
		if trimmed == "" || trimmed == "Optional Parameters" || trimmed == "-------------------" {
			if trimmed == "Optional Parameters" {
				state = stateParams
			}
			continue
		}

		if state == stateHeader {
			// Input/Output lines.
			if strings.HasPrefix(trimmed, "Input") || strings.HasPrefix(trimmed, "Output") {
				inputOutput = append(inputOutput, trimmed)
			}
			continue
		}

		// state == stateParams: alternate between param-name lines and description lines.
		if pendingParam == nil {
			// This line is a parameter name, possibly with a range: "timePeriod:(From 2 to 100000)"
			name, rang := parseParamLine(trimmed)
			pendingParam = &param{name: name, rang: rang}
		} else {
			// This line is the description for the pending parameter.
			pendingParam.desc = trimmed
			params = append(params, *pendingParam)
			pendingParam = nil
		}
	}
	// Flush a parameter that had no description line.
	if pendingParam != nil {
		params = append(params, *pendingParam)
	}

	// Assemble the final comment.
	var out []string
	out = append(out, lines[0])
	for _, line := range inputOutput {
		out = append(out, "", line)
	}
	if len(params) > 0 {
		out = append(out, "", "Parameters:")
		for _, p := range params {
			item := "  - " + p.name
			if p.rang != "" {
				item += " (" + p.rang + ")"
			}
			if p.desc != "" {
				item += ": " + p.desc
			}
			out = append(out, item)
		}
	}
	return strings.Join(out, "\n")
}

// reFromTo matches "From X to Y" or "From X to Y" range expressions in param lines.
var reFromTo = regexp.MustCompile(`(?i)From\s+`)

// parseParamLine splits "timePeriod:(From 2 to 100000)" into name="timePeriod" and
// rang="2 to 100000". Range is empty for params like "mAType:".
func parseParamLine(line string) (name, rang string) {
	colon := strings.IndexByte(line, ':')
	if colon < 0 {
		return line, ""
	}
	name = line[:colon]
	rest := strings.TrimSpace(line[colon+1:])
	// Strip surrounding parens if present.
	rest = strings.TrimPrefix(rest, "(")
	rest = strings.TrimSuffix(rest, ")")
	rest = strings.TrimSpace(rest)
	// Strip leading "From " (case-insensitive).
	rest = reFromTo.ReplaceAllString(rest, "")
	return name, rest
}

// outBufParamName derives a short buffer parameter name from an output GoName.
// e.g. "outMACD" → "macdBuf", "outRealUpperBand" → "upperBandBuf", "outAroonDown" → "aroonDownBuf".
func outBufParamName(goName string) string {
	s := goName
	// Strip "out" prefix.
	s = strings.TrimPrefix(s, "out")
	// Strip "Real" prefix if followed by an uppercase letter (it's a filler word, not semantic).
	if strings.HasPrefix(s, "Real") && len(s) > 4 && s[4] >= 'A' && s[4] <= 'Z' {
		s = s[4:]
	}
	if s == "" {
		return goName + "Buf"
	}
	// Find the leading uppercase run.
	i := 0
	for i < len(s) && s[i] >= 'A' && s[i] <= 'Z' {
		i++
	}
	var base string
	switch {
	case i == 0:
		base = s
	case i == len(s):
		// All uppercase (e.g. "MACD") — fully lowercase.
		base = strings.ToLower(s)
	case i == 1:
		// Single leading uppercase (e.g. "UpperBand") — lowercase first char.
		base = strings.ToLower(s[:1]) + s[1:]
	default:
		// Mixed run (e.g. "MACDSignal", "MACDHist") — lowercase all but the last
		// uppercase char, which starts the next CamelCase word.
		base = strings.ToLower(s[:i-1]) + s[i-1:]
	}
	return base + "Buf"
}

